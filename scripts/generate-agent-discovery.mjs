import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const packageJson = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const tauriConfig = JSON.parse(readFileSync(join(root, "src-tauri", "tauri.conf.json"), "utf8"));
const previewConfig = JSON.parse(
  readFileSync(join(root, "src-tauri", "tauri.preview.conf.json"), "utf8")
);
const version = packageJson.version;

function manifestFor(config) {
  return {
    schemaVersion: 2,
    productName: config.productName,
    identifier: config.identifier,
    version,
    cli: {
      // The same manifest format is consumed on every platform even though Preview is
      // currently Windows-only, so keep both paths truthful for future expansion.
      relativePath: {
        windows: "plvs-cli.exe",
        macos: "Contents/MacOS/plvs-cli",
      },
      doctor: ["doctor", "--json"],
    },
  };
}

function nsisDefinesFor(config, registryName) {
  return `; Generated by scripts/generate-agent-discovery.mjs. Do not edit by hand.
!define PLVS_AGENT_PRODUCT_NAME "${config.productName}"
!define PLVS_AGENT_IDENTIFIER "${config.identifier}"
!define PLVS_AGENT_VERSION "${version}"
!define PLVS_AGENT_REG_KEY "Software\\SounDoer\\${registryName}"
`;
}

function installerHook(defines) {
  return `; Generated by scripts/generate-agent-discovery.mjs. Do not edit by hand.
; Keep the finish-page desktop shortcut opt-in unchecked by default.
!define MUI_FINISHPAGE_SHOWREADME_NOTCHECKED

; BEGIN GENERATED PLVS AGENT DISCOVERY
${defines.trimEnd()}
; END GENERATED PLVS AGENT DISCOVERY

!macro NSIS_HOOK_POSTINSTALL
  WriteRegStr HKCU "\${PLVS_AGENT_REG_KEY}" "ProductName" "\${PLVS_AGENT_PRODUCT_NAME}"
  WriteRegStr HKCU "\${PLVS_AGENT_REG_KEY}" "Identifier" "\${PLVS_AGENT_IDENTIFIER}"
  WriteRegStr HKCU "\${PLVS_AGENT_REG_KEY}" "Version" "\${PLVS_AGENT_VERSION}"
  WriteRegStr HKCU "\${PLVS_AGENT_REG_KEY}" "InstallDir" "$INSTDIR"
  WriteRegStr HKCU "\${PLVS_AGENT_REG_KEY}" "CliPath" "$INSTDIR\\plvs-cli.exe"
!macroend

!macro NSIS_HOOK_POSTUNINSTALL
  DeleteRegKey HKCU "\${PLVS_AGENT_REG_KEY}"
!macroend
`;
}

const releaseManifest = manifestFor(tauriConfig);
const previewManifest = manifestFor(previewConfig);

writeFileSync(
  join(root, "src-tauri", "plvs-agent.json"),
  `${JSON.stringify(releaseManifest, null, 2)}\n`
);
writeFileSync(
  join(root, "src-tauri", "plvs-preview-agent.json"),
  `${JSON.stringify(previewManifest, null, 2)}\n`
);

const nsisDefines = nsisDefinesFor(tauriConfig, "PLVS");
const previewNsisDefines = nsisDefinesFor(previewConfig, "PLVS Preview");

writeFileSync(join(root, "src-tauri", "nsis", "agent-discovery.nsh"), nsisDefines);

const hookPath = join(root, "src-tauri", "nsis", "installer-hooks.nsh");
const hook = readFileSync(hookPath, "utf8");
const beginMarker = "; BEGIN GENERATED PLVS AGENT DISCOVERY";
const endMarker = "; END GENERATED PLVS AGENT DISCOVERY";
const generatedBlock = `${beginMarker}\n${nsisDefines.trimEnd()}\n${endMarker}`;
const markerPattern = new RegExp(`${beginMarker}[\\s\\S]*?${endMarker}`);
if (!markerPattern.test(hook)) {
  throw new Error("installer-hooks.nsh is missing the PLVS agent discovery marker block");
}
writeFileSync(hookPath, hook.replace(markerPattern, generatedBlock));
writeFileSync(
  join(root, "src-tauri", "nsis", "preview-installer-hooks.nsh"),
  installerHook(previewNsisDefines)
);

console.log("Wrote src-tauri/plvs-agent.json");
console.log("Wrote src-tauri/plvs-preview-agent.json");
console.log("Wrote src-tauri/nsis/agent-discovery.nsh");
console.log("Updated src-tauri/nsis/installer-hooks.nsh");
console.log("Wrote src-tauri/nsis/preview-installer-hooks.nsh");
