#!/usr/bin/env node

import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inventoryPath = join(repoRoot, "licenses", "DEPENDENCY-INVENTORY.txt");

function sha256(content) {
  return createHash("sha256").update(content).digest("hex");
}

function comparePackages(left, right) {
  return (
    left.name.localeCompare(right.name, "en") ||
    left.version.localeCompare(right.version, "en", { numeric: true }) ||
    (left.path || "").localeCompare(right.path || "", "en")
  );
}

export function collectRustRuntimePackages(metadata) {
  const packageById = new Map(metadata.packages.map((pkg) => [pkg.id, pkg]));
  const nodeById = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
  const appPackage = metadata.packages.find(
    (pkg) => metadata.workspace_members.includes(pkg.id) && pkg.name === "plvs"
  );
  if (!appPackage) throw new Error("Cargo metadata does not contain the PLVS workspace package");

  const included = new Set([appPackage.id]);
  const pending = [appPackage.id];
  while (pending.length > 0) {
    const id = pending.pop();
    for (const dependency of nodeById.get(id)?.deps || []) {
      const isRuntimeDependency = dependency.dep_kinds.some(({ kind }) => kind === null);
      if (!isRuntimeDependency || included.has(dependency.pkg)) continue;
      included.add(dependency.pkg);
      pending.push(dependency.pkg);
    }
  }

  return [...included].map((id) => packageById.get(id)).sort(comparePackages);
}

export function collectJavascriptProductionPackages(packageLock) {
  return Object.entries(packageLock.packages)
    .filter(([path, metadata]) => path && metadata.dev !== true)
    .map(([path, metadata]) => ({
      name: path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length),
      version: metadata.version,
      license: metadata.license || "UNKNOWN",
      path,
    }))
    .sort(comparePackages);
}

function renderRustPackage(pkg) {
  const authors = pkg.authors?.length ? pkg.authors.join("|") : "UNKNOWN";
  const repository = pkg.repository || pkg.homepage || "UNKNOWN";
  return `${pkg.name} ${pkg.version} | ${pkg.license || "UNKNOWN"} | ${authors} | ${repository}`;
}

function renderJavascriptPackage(pkg) {
  return `${pkg.name} ${pkg.version} | ${pkg.license}`;
}

export async function generateDependencyInventory() {
  const cargoLock = await readFile(join(repoRoot, "src-tauri", "Cargo.lock"));
  const packageLockBytes = await readFile(join(repoRoot, "package-lock.json"));
  const packageLock = JSON.parse(packageLockBytes.toString("utf8"));
  const cargo = spawnSync(
    "cargo",
    [
      "metadata",
      "--format-version",
      "1",
      "--locked",
      "--manifest-path",
      "src-tauri/Cargo.toml",
    ],
    { cwd: repoRoot, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }
  );
  if (cargo.status !== 0) {
    throw new Error(`cargo metadata failed:\n${cargo.stderr || cargo.stdout}`);
  }

  const rustPackages = collectRustRuntimePackages(JSON.parse(cargo.stdout));
  const javascriptPackages = collectJavascriptProductionPackages(packageLock);
  return [
    "PLVS PRODUCTION DEPENDENCY LICENSE INVENTORY",
    "",
    "Generated by: node scripts/generate-license-inventory.mjs",
    "Sources: src-tauri/Cargo.lock and package-lock.json",
    `Cargo.lock SHA-256: ${sha256(cargoLock)}`,
    `package-lock.json SHA-256: ${sha256(packageLockBytes)}`,
    "",
    "This is a reproducible engineering inventory of upstream package metadata, not legal advice.",
    "Rust excludes development and build dependencies. JavaScript excludes entries marked dev-only",
    "in package-lock.json. Platform-specific runtime dependencies for both shipped platforms remain",
    "included. Full standard license texts and component-specific notices are distributed beside",
    "this file.",
    "",
    `RUST RUNTIME DEPENDENCIES (${rustPackages.length})`,
    "",
    ...rustPackages.map(renderRustPackage),
    "",
    `JAVASCRIPT PRODUCTION DEPENDENCIES (${javascriptPackages.length})`,
    "",
    ...javascriptPackages.map(renderJavascriptPackage),
    "",
  ].join("\n");
}

async function main() {
  const mode = process.argv[2];
  if (mode !== "--write" && mode !== "--check") {
    console.error("Usage: node scripts/generate-license-inventory.mjs --write|--check");
    process.exit(2);
  }

  const generated = await generateDependencyInventory();
  if (mode === "--write") {
    await writeFile(inventoryPath, generated);
    console.log(`Wrote ${inventoryPath}`);
    return;
  }

  const current = (await readFile(inventoryPath, "utf8")).replace(/\r\n/g, "\n");
  if (current !== generated) {
    console.error(
      "licenses/DEPENDENCY-INVENTORY.txt is stale. Run: npm run licenses:generate"
    );
    process.exit(1);
  }
  console.log("License dependency inventory is current");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
